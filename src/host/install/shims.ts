// The commands on PATH. Each one is a tiny script that reads the two pointer files and runs the version they name, so
// an update never has to rewrite a shim: it only moves the pointers. A .cmd for cmd.exe and PowerShell, and a POSIX
// script (same name, no extension) for Git Bash.
import path from 'node:path';
import { z } from 'zod';
import { fail } from '../../core/util/index.js';
import { writeFileAtomic } from '../../shared/io/index.js';
import type { InstallLayout } from './layout.js';

const COMMAND_NAME = /^[a-z0-9][a-z0-9-]*$/i;

/**
 * The text of one shim. `target` is the program's path inside the package (dist/bin/<name>.js unless the package.json
 * bin entry says otherwise).
 */
export function shimText(name: string, kind: 'cmd' | 'sh', target: string = 'dist/bin/' + name + '.js'): string {
  if (!COMMAND_NAME.test(name)) fail('"' + name + '" is not a command name.');
  if (kind === 'sh') {
    return [
      '#!/bin/sh',
      '# Generated by windows-development-sandbox. Runs the version that active-version points to.',
      'root=$(cd "$(dirname "$0")/.." && pwd)',
      'node_version=$(tr -d "\\r\\n" < "$root/active-node")',
      'version=$(tr -d "\\r\\n" < "$root/active-version")',
      'exec "$root/node/$node_version/node.exe" "$root/versions/$version/package/' + target + '" "$@"',
      '',
    ].join('\n');
  }
  const windowsTarget = target.split('/').join('\\');
  return [
    '@echo off',
    'setlocal',
    'set /p V=<"%~dp0..\\active-version"',
    'set /p N=<"%~dp0..\\active-node"',
    '"%~dp0..\\node\\%N%\\node.exe" "%~dp0..\\versions\\%V%\\package\\' + windowsTarget + '" %*',
    '',
  ].join('\r\n');
}

const BinSchema = z.object({ bin: z.record(z.string(), z.string()).optional() });

/** The commands a package.json declares (name -> program path inside the package). Invalid names are refused. */
export function readBins(packageJson: unknown): Record<string, string> {
  const parsed = BinSchema.safeParse(packageJson);
  if (!parsed.success) fail('package.json has a "bin" entry that is not a map of names to paths.');
  const bins = parsed.data.bin ?? {};
  for (const name of Object.keys(bins))
    if (!COMMAND_NAME.test(name)) fail('package.json declares a command with an invalid name: ' + name);
  return bins;
}

/** Writes <bin>.cmd and <bin> for every command in `bins` (name -> program path inside the package). */
export function writeShims(layout: InstallLayout, bins: Record<string, string>): void {
  for (const [name, target] of Object.entries(bins)) {
    writeFileAtomic(path.join(layout.binDir, name + '.cmd'), shimText(name, 'cmd', target));
    writeFileAtomic(path.join(layout.binDir, name), shimText(name, 'sh', target));
  }
}
